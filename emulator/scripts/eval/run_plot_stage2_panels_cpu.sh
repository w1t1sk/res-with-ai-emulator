#!/bin/bash

set -euo pipefail

if [[ -n "${UPD_EMULATOR_REPO_ROOT:-}" ]]; then
  REPO_ROOT="$UPD_EMULATOR_REPO_ROOT"
elif [[ -n "${SLURM_SUBMIT_DIR:-}" ]]; then
  REPO_ROOT="$SLURM_SUBMIT_DIR"
else
  REPO_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
fi
export UPD_EMULATOR_REPO_ROOT="$REPO_ROOT"
source "$REPO_ROOT/scripts/utils/_common.sh"
activate_env_if_needed
PYTHON_BIN=$(resolve_python_bin)

export PYTHONPATH="$REPO_ROOT/src:${PYTHONPATH:-}"
export PYTHONUNBUFFERED="${PYTHONUNBUFFERED:-1}"
export OMP_NUM_THREADS="${OMP_NUM_THREADS:-8}"
export MPLCONFIGDIR="${MPLCONFIGDIR:-/tmp/upd_emulator_mpl_${USER:-user}}"
export XDG_CACHE_HOME="${XDG_CACHE_HOME:-/tmp/upd_emulator_xdg_cache_${USER:-user}}"
export CUDA_VISIBLE_DEVICES=""
mkdir -p "$MPLCONFIGDIR"
mkdir -p "$XDG_CACHE_HOME"

export UPD_EMULATOR_DATA_ROOT="${UPD_EMULATOR_DATA_ROOT:-/home/nishidh/fuxi-ens/data}"
export UPD_EMULATOR_PLOT_RUN="${UPD_EMULATOR_PLOT_RUN:-run16}"
export UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_CKPT="${UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_CKPT:-$REPO_ROOT/checkpoints/stage2/latent_hierswin_rollout_best.pt}"
export UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_STATS_PATH="${UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_STATS_PATH:-$REPO_ROOT/resources/stats/exac_input_stats.pt}"
export UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_PLOT_DIR="${UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_PLOT_DIR:-$REPO_ROOT/plots/panels}"
export UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_PLOT_LEADS="${UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_PLOT_LEADS:-3 7 11}"
export UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_SAMPLE_INDEX="${UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_SAMPLE_INDEX:-0}"
export UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_ENSEMBLE_MEMBERS="${UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_ENSEMBLE_MEMBERS:-8}"

"$PYTHON_BIN" "$REPO_ROOT/scripts/eval/plot_stage2_panels.py" \
  --data-root "$UPD_EMULATOR_DATA_ROOT" \
  --run "$UPD_EMULATOR_PLOT_RUN" \
  --checkpoint-path "$UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_CKPT" \
  --stats-path "$UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_STATS_PATH" \
  --output-dir "$UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_PLOT_DIR" \
  --lead-times $UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_PLOT_LEADS \
  --sample-index "$UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_SAMPLE_INDEX" \
  --ensemble-members "$UPD_EMULATOR_STAGE2_LATENT_HIERSWIN_ENSEMBLE_MEMBERS" \
  --device cpu \
  "$@"
